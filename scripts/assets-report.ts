import fs from "fs";
import path from "path";

import { writeReviewList } from "./curriculum/ai-audio";
import { createBuilder } from "./curriculum/build";
import { loadCurriculum } from "./curriculum/load";

// Writes checklists of the audio and image files the curriculum refers to
// but that don't exist in /public yet. Re-run after adding files or lessons:
//   npm run assets:report

const OUT_DIR = path.join(process.cwd(), "docs", "assets");

const units = loadCurriculum();
const builder = createBuilder(units);
units.forEach((u) => u.lessons.forEach((l) => builder.buildLesson(u, l)));

const audio = builder.missingAudio();
const images = builder.missingImages();

const cell = (s?: string) => (s ?? "").replace(/\|/g, "\\|");

const byUnit = <T extends { usedIn: string }>(rows: T[]) => {
  const groups = new Map<string, T[]>();
  for (const row of rows) {
    const unit = row.usedIn.split(" › ")[0];
    groups.set(unit, [...(groups.get(unit) ?? []), row]);
  }
  return groups;
};

const audioMd = [
  "# Audio still to record",
  "",
  "Generated by `npm run assets:report` - don't edit by hand, re-run it instead.",
  "See [RECORDING_GUIDE.md](../RECORDING_GUIDE.md) for how to record.",
  "",
  `**${audio.length} files missing.** Save each one at the exact path shown (inside \`public/\`).`,
  "",
];

// Single letters and words unlock the most practice per minute recorded.
const priorities = [
  {
    title: "Priority 1 - letters & single words",
    rows: audio.filter((r) => r.kind === "letter" || r.kind === "word"),
  },
  {
    title: "Priority 2 - short phrases & reading drills",
    rows: audio.filter((r) => r.kind === "phrase" || r.kind === "reading"),
  },
  {
    title: "Priority 3 - full sentences & dialogue lines",
    rows: audio.filter((r) => r.kind === "sentence"),
  },
];

for (const { title, rows } of priorities) {
  audioMd.push(`# ${title} (${rows.length})`, "");
  for (const [unit, unitRows] of Array.from(byUnit(rows))) {
    audioMd.push(
      `## ${unit}`,
      "",
      "| Done | Say this (Urdu) | Romanized | Meaning | Save as |",
      "|---|---|---|---|---|"
    );
    for (const r of unitRows)
      audioMd.push(
        `| [ ] | ${cell(r.urdu)} | ${cell(r.roman)} | ${cell(r.english)} | \`public${r.file}\` |`
      );
    audioMd.push("");
  }
}

const imageMd = [
  "# Images still to create",
  "",
  "Generated by `npm run assets:report` - don't edit by hand, re-run it instead.",
  "",
  `**${images.length} files missing.** Square SVG (or PNG), transparent background.`,
  "",
  "| Done | Picture of | Save as | Used in |",
  "|---|---|---|---|",
  ...images.map(
    (r) =>
      `| [ ] | ${cell(r.english)} | \`public${r.file}\` | ${cell(r.usedIn)} |`
  ),
  "",
];

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, "audio-todo.md"), audioMd.join("\n"));
fs.writeFileSync(path.join(OUT_DIR, "image-todo.md"), imageMd.join("\n"));

console.log(`Missing audio:  ${audio.length}  → docs/assets/audio-todo.md`);
console.log(`Missing images: ${images.length}  → docs/assets/image-todo.md`);

const review = writeReviewList();
console.log(
  `AI clips to review: ${review.toReview} of ${review.total}  → docs/assets/ai-audio-review.md`
);
